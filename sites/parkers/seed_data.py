#!/usr/bin/env python3
"""Parkers mirror — deterministic seed builder.

Reads the captured upstream snapshot from scraped_data/*.json and materializes
it into the SQLite seed DB. Idempotent: every seed function early-returns when
its tables are already populated. Run with PYTHONHASHSEED=0 for byte-identical
rebuilds.

Data provenance: every row comes from the 2026-09-24 parkers.co.uk capture
(review JSON-LD, spec tables, CAP valuation year/version lists, cars-for-sale
result cards, news articles, owner reviews, insurance group tables, and real
free-valuation anchors). Valuation ranges for (derivative, year) pairs without
a captured upstream anchor are generated by a fixed depreciation curve
anchored to the captured price-when-new and calibrated against the captured
anchors; the generated numbers live in the seed DB, which is the single
runtime source of truth.
"""
import json
