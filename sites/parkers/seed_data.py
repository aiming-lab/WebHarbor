JUNK_PARAGRAPH_MARKERS = (
    # stylesheet blobs accidentally captured by the section scraper
    '@media', 'base64', ')}@',
    # site footer / nav boilerplate captured after the section body
    'Bauer Media Group consists', '© 1972', 'Do not sell my information',
    'VAT no 918 5617 01', 'authorised and regulated for credit broking',
    'Sign up to receive the PARKERS newsletters', 'Privacy settings',
    'Follow Parkers on Google', 'Add Parkers as a preferred source',
    'Enter your email here', 'Your email has been successfully submitted',
    'Oops, something went wrong', 'You can unsubscribe at any time',
)


def clean_paragraphs(paras):
    """Drop stylesheet/footer artifacts from captured section paragraphs so the
    rendered review sections contain only the upstream article prose."""
    out = []
    for p in paras or []:
        p = (p or '').strip()
        if not p:
            continue
        if any(m in p for m in JUNK_PARAGRAPH_MARKERS):
            continue
        # bare nav-label runs captured from the page chrome (no prose)
        if '\n \n' in p and len(re.sub(r'[^A-Za-z]', '', p)) < 120 and not re.search(r'[.!?]', p):
            continue
        out.append(p)
    return out


