def normalize_index_layout(db):
    """Re-create every explicit secondary index in a deterministic order.

    SQLAlchemy iterates ``table.indexes`` (a set of Index objects) when it
    issues CREATE INDEX, so the physical root-page assignment of same-table
    indexes varies run to run (object ids feed the set order even with
    PYTHONHASHSEED=0). Dropping and re-creating the indexes sorted by name
    makes the layout — and therefore the seed file bytes — reproducible:
    the freed pages are re-used deterministically from the freelist.
    """
    import sqlalchemy as sa
    inspector = sa.inspect(db.engine)
    existing = {ix['name'] for t in inspector.get_table_names()
                for ix in inspector.get_indexes(t)}
    with db.engine.begin() as conn:
        for table in sorted(db.metadata.tables.values(), key=lambda t: t.name):
            for index in sorted(table.indexes, key=lambda i: i.name):
                if index.name not in existing:
                    continue
                cols = ', '.join(f'"{c.name}"' for c in index.columns)
                conn.exec_driver_sql(f'DROP INDEX IF EXISTS "{index.name}"')
                conn.exec_driver_sql(
                    f'CREATE INDEX "{index.name}" ON "{table.name}" ({cols})')


