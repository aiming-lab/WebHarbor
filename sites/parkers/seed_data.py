BASE_DIR = os.path.dirname(os.path.abspath(__file__))
SCRAPE = os.path.join(BASE_DIR, 'scraped_data')

BENCHMARK_TODAY = date(2026, 9, 24)
BENCHMARK_YEAR = 2026


def load(name):
    path = os.path.join(SCRAPE, name)
    if not os.path.exists(path):
        return None
    with open(path) as f:
        return json.load(f)


_IMAGE_MAP = None


def local_image(url):
    """Translate a captured upstream image URL to its shipped local path."""
    global _IMAGE_MAP
    if _IMAGE_MAP is None:
        _IMAGE_MAP = load('image_map.json') or {}
    if not url:
        return ''
    url = re.sub(r'\?.*$', '', url)
    return '/static/images/' + _IMAGE_MAP.get(url, '')


def slugify(text):
    """Upstream slug convention: dots removed, other non-alnum -> hyphen."""
    text = (text or '').lower().replace('.', '')
    text = re.sub(r'[^a-z0-9]+', '-', text)
    return text.strip('-')


def canonical_tokens(slug):
    """Sorted token multiset so engine-first and trim-first names match."""
    toks = []
    for t in (slug or '').split('-'):
        if not t:
            continue
        if t.endswith('dr'):
            t = t[:-1]
        toks.append(t)
    return tuple(sorted(toks))


def parse_price(text):
    """'£32,125' -> 32125; '£8,880 - £34,048' -> (8880, 34048)"""
    if not text:
        return None
    nums = [int(n.replace(',', '')) for n in re.findall(r'£([\d,]+)', str(text))]
    if not nums:
        return None
    if len(nums) >= 2:
        return nums[0], nums[-1]
    return nums[0]


def parse_price_first(text):
    p = parse_price(text)
    if isinstance(p, tuple):
        return p[0]
    if p is None:
        m = re.search(r'([\d,]+)', str(text or ''))
        return int(m.group(1).replace(',', '')) if m else None
    return p


def parse_int(text):
    if text is None:
        return None
    m = re.search(r'-?\d+', str(text).replace(',', ''))
    return int(m.group()) if m else None


# ---------------------------------------------------------------------------
# Valuation curve (deterministic; calibrated against captured anchors)
# ---------------------------------------------------------------------------

def depreciation_factor(age):
    """Fraction of original price retained after `age` years.

    Calibrated against captured Parkers free-valuation anchors (e.g. a
    2019/19 Fiesta Zetec retains ~21% of its new price by 2026): ~37% lost
    in year one, then ~18% per year, flattening near 8%.
    """
    if age <= 0:
        return 1.0
    factor = 0.63 * (0.82 ** (age - 1))
    return max(0.06, round(factor, 4))


def compute_valuation(price_new, plate_year):
    """Private/dealer/part-ex ranges for a (price_new, year) pair."""
    age = BENCHMARK_YEAR - plate_year
    if age < 0:
        age = 0
    mid = int(round(price_new * depreciation_factor(age), -1))
    private_low = int(round(mid * 0.86, -1))
    private_high = int(round(mid * 1.14, -1))
    dealer_mid = int(round(mid * 1.25, -1))
    dealer_low = int(round(dealer_mid * 0.97, -1))
    dealer_high = int(round(dealer_mid * 1.03, -1))
    part_low = int(round(mid * 0.93, -1))
    part_high = int(round(mid * 1.02, -1))
    return private_low, private_high, dealer_low, dealer_high, part_low, part_high


