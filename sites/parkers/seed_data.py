    specs = load('specs.json') or {}
    anchors = load('valanchors.json') or []
    anchor_map = {}
    for a in anchors:
        if a.get('private_low'):
            key_slug = a.get('slug') or slugify(a['version'])
            anchor_map[(a['gen'], a['year'], key_slug)] = a

    for key, rec in sorted(specs.items()):
        mk_slug, mo_slug = key.split('/')
        from app import CarModel, Make
        m = (CarModel.query.join(Make, CarModel.make_id == Make.id)
             .filter(Make.slug == mk_slug, CarModel.slug == mo_slug).first())
        if not m:
            continue
        for grec in rec.get('generations', []):
            gslug = grec['gen_slug']
            gname = grec['name']
            years_label = grec.get('name', '')
            ym = re.search(r'\((\d{2,4})\s*(?:-|on)', gname) or re.search(r'\((\d{4})\s*-\s*(\d{4})\)', gname)
            year_from = None
            ym2 = re.search(r'\((\d{2})\+?[- ]', gname)
            if ym2:
                yy = int(ym2.group(1))
                year_from = 2000 + yy if yy < 50 else 1900 + yy
            m2 = re.search(r'\((\d{4})', gname)
            if year_from is None and m2:
                year_from = int(m2.group(1))
            m3 = re.search(r'-(\d{2})\)', gname)
            year_to = BENCHMARK_YEAR
            if m3:
                yy = int(m3.group(1))
                year_to = 2000 + yy if yy < 50 else 1900 + yy
