GUIDE_HEADER_PAT = re.compile(
    r'^(the best|best|other|one to|also|winner|highly|editor|top|our|all the|cars? (to|in)|'
    r'[^a-z0-9]|.*recommended by parkers$)', re.I)


def clean_guide_ranked(items):
    out = []
    for it in items:
        it = (it or '').strip()
        if not it or len(it) > 70:
            continue
        if GUIDE_HEADER_PAT.match(it):
            continue
        out.append(it)
    return out[:12]


